	AREA RESET, DATA, READONLY
	EXPORT __Vectors
	
__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN 
	
	AREA mycode, CODE, READONLY
	ENTRY
	EXPORT Reset_Handler
	
Reset_Handler
	LDR R0,=SRC
	; LDR R3,=DST
	MOV R1, #0
	MOV R3, #10
	
UP
	LDR R2, [R0], #4
	ADDS R1, R2
	ADC R4, #0
	SUB R3, #1
	BNE UP
	
STOP 
	B STOP

SRC DCD 0xFFFFFFFF, 0x11111111, 0x11111111, 0x11111111, 0x11111111, 0x11111111, 0x11111111, 0x11111111, 0x11111111, 0x11111111
	AREA mydata, DATA, READWRITE

DST DCD 0
	END