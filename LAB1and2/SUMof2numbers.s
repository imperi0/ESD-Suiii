	AREA RESET, DATA, READONLY
	EXPORT __Vectors
	
__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN 
	
	AREA mycode, CODE, READONLY
	ENTRY
	EXPORT Reset_Handler
	
Reset_Handler
	LDR R0,=VAL1
	LDR R1,=VAL2
	LDR R3,=DST
	MOV R4, #4
	MOV R5, #0
	MOV R8, #0

	; SOLUTION 1

UP
	LDR R6, [R0], #4
	LDR R7, [R1], #4
	ADDS R5, R6, R7
	ADDS R5, R8
	ADC R8, 0
	STR R5, [R3], #4
	SUBS R4, #1
	BNE UP
	
STOP 
	B STOP

VAL1 DCD 0xFFFFFFFF, 0xFFFFFFFF, 0x11111111, 0x11111111
VAL2 DCD 0X11111111, 0x11111111, 0x11111111, 0x11111111
	AREA mydata, DATA, READWRITE

DST DCD 0
	END